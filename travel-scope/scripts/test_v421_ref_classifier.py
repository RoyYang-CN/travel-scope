class ClassifierMatrixTests(unittest.TestCase):
    """§17.7 W1R-B 7：Google/Apple/OSM 的 entity/search/coordinate/home/invalid 逐例实际输出。"""

    def test_every_case_matches_the_isolated_probe(self):
        drift = []
        for entry in MATRIX:
            found = classify(entry)
            for dimension, expected, actual in (
                    ("kind", entry["kind"], found["kind"]),
                    ("reason_code", entry["reason"], found["reason_code"]),
                    ("canonical_locator", entry["locator"], found["canonical_locator"])
                    if entry["surface"] == "url" else ("kind", entry["kind"], found["kind"])):
                if expected != actual:
                    drift.append({"case": entry["case"], "dimension": dimension,
                                  "expected": expected, "actual": actual})
        self.assertEqual(drift, [], json.dumps(drift, ensure_ascii=False)[:1600])

    def test_matrix_covers_all_three_providers_and_five_kinds(self):
        providers = {entry["required_provider"] for entry in URL_ROWS if entry["required_provider"]}
        kinds = {entry["kind"] for entry in MATRIX}
        self.assertEqual(providers, {"google", "apple", "osm"})
        self.assertEqual(kinds, {"entity", "search", "coordinate", "home", "invalid"})
        for kind in kinds:
            for provider in ("google", "apple", "osm"):
                hit = [entry for entry in URL_ROWS
                       if entry["required_provider"] == provider and entry["kind"] == kind]
